-- Staff hierarchy sample data for practising recursive CTEs
-- 100 staff, 30 managers (including the top-level manager, staff_id 1,
-- who has no manager). Some managers report to other managers.

DROP TABLE IF EXISTS staff;

CREATE TABLE staff (
    staff_id    integer PRIMARY KEY,
    first_name  text NOT NULL,
    second_name text NOT NULL,
    manager_id  integer REFERENCES staff (staff_id)
);

CREATE INDEX staff_manager_id_idx ON staff (manager_id);

